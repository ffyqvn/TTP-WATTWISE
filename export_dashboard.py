"""
Turn the model's predictions into data the WattWise dashboard can show.

Run:  python export_dashboard.py
      python export_dashboard.py --day 2026-10-28 --hour 14 --out ..\\dashboard\\today_data.js

Needs (in the current folder): test_predictions.csv (made by train_model.py)
                               energy_data.csv     (for room type and capacity)
Creates: today_data.js  (put it in the same folder as the dashboard's index.html)
"""
import argparse, json
import pandas as pd

ap = argparse.ArgumentParser()
ap.add_argument("--pred", default="test_predictions.csv")
ap.add_argument("--raw", default="new_energy_data.csv")
ap.add_argument("--day", help="YYYY-MM-DD, default = latest day in the predictions")
ap.add_argument("--hour", type=int, help="'now' hour 0-23, default = last hour of that day")
ap.add_argument("--out", default="today_data.js")
a = ap.parse_args()

pred = pd.read_csv(a.pred, parse_dates=["timestamp"])
raw = pd.read_csv(a.raw, usecols=["room_id", "room_type", "capacity"]).drop_duplicates("room_id")
pred = pred.merge(raw, on="room_id", how="left")

day = pd.Timestamp(a.day).date() if a.day else pred.timestamp.max().date()
d = pred[pred.timestamp.dt.date == day].copy()
if d.empty:
    raise SystemExit(f"No rows for {day}. Days available: {sorted(set(pred.timestamp.dt.date))}")
d["hour"] = d.timestamp.dt.hour
now = a.hour if a.hour is not None else int(d.hour.max())

rooms = []
for room, g in d.groupby("room_id"):
    g = g.sort_values("hour")
    cur = g[g.hour == now]
    if cur.empty:
        continue
    cur = cur.iloc[0]
    pred_hourly = g.set_index("hour").pred_a.reindex(range(24)).fillna(0).round(3).tolist()
    actual_hourly = g[g.hour <= now].set_index("hour").power_kw.reindex(range(now + 1)).fillna(0).round(3).tolist()
    rooms.append({
        "room_name": room,
        "room_type": cur.room_type,
        "occupancy": int(cur.occupancy),
        "capacity": int(cur.capacity),
        "power_kw": round(float(cur.power_kw), 3),
        "predicted_kw": round(float(cur.pred_a), 3),
        "flagged": bool(cur.flagged),            # the model's own anomaly decision
        "predicted_hourly": pred_hourly,
        "actual_hourly": actual_hourly,
    })

out = {
    "asOf": f"{day:%d %b %Y}, {now:02d}:00",
    "nowHour": now,
    "reductionPct": None,   # needs a pre-deployment baseline; the dashboard shows a dash
    "rooms": rooms,
}
with open(a.out, "w", encoding="utf-8") as f:
    f.write("// Generated by export_dashboard.py. Do not edit by hand.\n")
    f.write("window.TODAY_DATA = " + json.dumps(out, indent=1) + ";\n")
flagged = [r["room_name"] for r in rooms if r["flagged"]]
print(f"Wrote {a.out}: {len(rooms)} rooms, {out['asOf']}. Flagged now: {flagged or 'none'}")